/* ---------------------------------------------------------------- layers */

export interface TextLayer {
  id: string;
  text: string;
  /** Line height in OLED pixels (8 = 1x Press Start 2P). Any value, not just multiples. */
  size: number;
  x: number;
  y: number;
  color: 0 | 1;
  font: FontId;
  /** How phone emoji become pixels: keep the drawing's details, or a filled silhouette. */
  emoji: "detail" | "solid";
}

const SKIP = new Set(["️", "︎"]);
const EMOJI_RE = /\p{Extended_Pictographic}|\p{Regional_Indicator}/u;
const segmenter =
  typeof Intl !== "undefined" && "Segmenter" in Intl
    ? new Intl.Segmenter(undefined, { granularity: "grapheme" })
    : null;

function graphemes(s: string): string[] {
  const parts = segmenter ? Array.from(segmenter.segment(s), (x) => x.segment) : Array.from(s);
  return parts.filter((g) => !SKIP.has(g));
}

const isEmoji = (g: string) => EMOJI_RE.test(g);

interface Glyph { rows: string[]; adv: number }

function glyphFor(ch: string, font: FontId): Glyph {
  if (font === "press") {
    const p = pressStartGlyph(ch);
    if (p) return { rows: p.split(" "), adv: 8 };
    const a = ARCADE[ch.toUpperCase()]; // until the font file has loaded
    if (a) return { rows: a.split(" "), adv: 8 };
  }
  return { rows: (FONT[ch] ?? UNKNOWN).split(" "), adv: 6 };
}

/* Phone emoji -> 1-bit, using the device's own emoji font. Cached per size. */
const emojiCache = new Map<string, Uint8Array>();
const EMOJI_FONTS = '"Apple Color Emoji","Segoe UI Emoji","Noto Color Emoji","Android Emoji",sans-serif';

function emojiBitmap(g: string, n: number, style: TextLayer["emoji"]): Uint8Array {
  const key = `${g}|${n}|${style}`;
  const hit = emojiCache.get(key);
  if (hit) return hit;
  const out = new Uint8Array(n * n);
  if (typeof document !== "undefined") {
    const S = n * 4; // draw big, then sample down for clean edges
    const c = document.createElement("canvas");
    c.width = S;
    c.height = S;
    const ctx = c.getContext("2d", { willReadFrequently: true });
    if (ctx) {
      ctx.textAlign = "center";
      ctx.textBaseline = "middle";
      ctx.font = `${Math.round(S * 0.86)}px ${EMOJI_FONTS}`;
      ctx.fillText(g, S / 2, S / 2 + S * 0.04);
      const d = ctx.getImageData(0, 0, S, S).data;
      for (let y = 0; y < n; y++) {
        for (let x = 0; x < n; x++) {
          // Average the 4x4 block that becomes this pixel
          let a = 0, lum = 0;
          for (let sy = 0; sy < 4; sy++)
            for (let sx = 0; sx < 4; sx++) {
              const i = ((y * 4 + sy) * S + (x * 4 + sx)) * 4;
              const al = d[i + 3] / 255;
              a += al;
              lum += (0.299 * d[i] + 0.587 * d[i + 1] + 0.114 * d[i + 2]) * al;
            }
          a /= 16;
          const l = a > 0 ? lum / 16 / a : 0;
          out[y * n + x] = style === "solid" ? (a >= 0.5 ? 1 : 0) : a >= 0.5 && l >= 95 ? 1 : 0;
        }
      }
    }
  }
  emojiCache.set(key, out);
  return out;
}

type Item = { kind: "glyph"; g: Glyph } | { kind: "emoji"; g: string };

function layout(l: TextLayer) {
  const s = l.size / 8;
  const gap = Math.max(1, Math.round(s));
  const lines = l.text.split("\n").map((line) =>
    graphemes(line).map<Item>((g) => (isEmoji(g) ? { kind: "emoji", g } : { kind: "glyph", g: glyphFor(g, l.font) })),
  );
  const adv = (it: Item) => (it.kind === "emoji" ? Math.round(l.size) + gap : it.g.adv * s);
  const widths = lines.map((items) => items.reduce((w, it) => w + adv(it), 0));
  const lineH = Math.round(l.size) + gap;
  return { s, lines, adv, widths, lineH };
}

/** Bounding box of a layer in OLED pixels. */
export function layerBounds(l: TextLayer): { x: number; y: number; w: number; h: number } {
  const { widths, lineH, lines } = layout(l);
  const w = Math.max(Math.round(l.size), Math.round(Math.max(0, ...widths)));
  return { x: Math.round(l.x), y: Math.round(l.y), w, h: lines.length * lineH - Math.max(1, Math.round(l.size / 8)) };
}

/** Draws a text layer onto a 128x64 one-byte-per-pixel buffer (in place). */
export function drawLayer(px: Uint8Array, l: TextLayer) {
  const { s, lines, adv, lineH } = layout(l);
  const n = Math.max(4, Math.round(l.size));
  const set = (x: number, y: number) => {
    if (x >= 0 && x < W && y >= 0 && y < H) px[y * W + x] = l.color;
  };
  lines.forEach((items, li) => {
    let cx = l.x;
    const top = Math.round(l.y + li * lineH);
    for (const it of items) {
      const left = Math.round(cx);
      if (it.kind === "emoji") {
        const bmp = emojiBitmap(it.g, n, l.emoji);
        for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) if (bmp[y * n + x]) set(left + x, top + y);
      } else {
        // Nearest-neighbour scaling keeps hard pixel edges at any size
        const gw = Math.round(it.g.rows[0].length * s);
        const gh = Math.round(it.g.rows.length * s);
        for (let ty = 0; ty < gh; ty++) {
          const row = it.g.rows[Math.min(it.g.rows.length - 1, Math.floor(ty / s))];
          for (let tx = 0; tx < gw; tx++) {
            if (row[Math.min(row.length - 1, Math.floor(tx / s))] === "#") set(left + tx, top + ty);
          }
        }
      }
      cx += adv(it);
    }
  });
}
